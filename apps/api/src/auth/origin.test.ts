import { expect, it } from 'vitest';
import { isOriginAllowed } from './origin.js';
it.each([
  {
    name: 'allows GET without origin or referer',
    method: 'get',
    origin: undefined,
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: true,
  },
  {
    name: 'allows a matching origin',
    method: 'POST',
    origin: 'https://www.example.com',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: true,
  },
  {
    name: 'allows a referer with a matching origin',
    method: 'POST',
    origin: undefined,
    referer: 'https://www.example.com:443/',
    allowedOrigin: 'https://www.example.com',
    expected: true,
  },
  {
    name: 'rejects a mismatching referer',
    method: 'POST',
    origin: undefined,
    referer: 'https://www.different-example.com/',
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a null origin',
    method: 'POST',
    origin: 'null',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a null origin AND referer',
    method: 'POST',
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a wrong host',
    method: 'POST',
    origin: 'https://www.different-example.com',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a wrong port',
    method: 'POST',
    origin: 'https://www.example.com:8443',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a wrong scheme',
    method: 'POST',
    origin: 'http://www.example.com',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a trailing slash on Origin',
    method: 'POST',
    origin: 'https://www.example.com/',
    referer: undefined,
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects an unparsable Referer',
    method: 'POST',
    origin: undefined,
    referer: 'not-a-valid-url',
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
  {
    name: 'rejects a mismatching Origin even with a matching Referer',
    method: 'POST',
    origin: 'https://www.different-example.com',
    referer: 'https://www.example.com/',
    allowedOrigin: 'https://www.example.com',
    expected: false,
  },
])('$name', ({ method, origin, referer, allowedOrigin, expected }) => {
  expect(isOriginAllowed(method, origin, referer, allowedOrigin)).toBe(expected);
});
